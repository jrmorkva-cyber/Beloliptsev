#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
fix-site-tree.py — приведение Astro-порта в соответствие с продом.

Дерево site/ в прод не собирается, но остаётся заряженной миной: однажды его
выпустят, и вместе с ним вернётся то, что в проде уже сознательно убрали.
Три проблемы:

1. Битый тип schema.org в 9 файлах: "ОриентирOrHistoricalBuilding" вместо
   "LandmarkOrHistoricalBuilding". Последствие моего же патчера англицизмов,
   который заменял слово landmark и съел тип внутри микроразметки.

2. Неподтверждаемый рейтинг «РГР Топ-3/Топ-4 из 1080». В проде его убрали
   сознательно (созвон 07.07) и заменили на «Аттестованный риэлтор-эксперт РГР» —
   формулировку, которая проверяется в реестре. В site/ старая осталась.
   Заодно «23 года практики» → «20+ лет», как в проде.

3. Canonical на /avangard/<slug>/ при том, что живые проиндексированные адреса —
   /modernizm/<slug>/. Владелец решил адреса не менять, значит в site/ canonical
   должен указывать туда же, иначе миграция 10 адресов однажды уедет случайно.

Usage: python tools/fix-site-tree.py [--dry]
"""
import os, re, sys, glob

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(BASE, "site", "src", "data")

# Порядок важен: длинные формы раньше коротких, иначе останутся хвосты.
RGR = [
    ("РГР Топ-3&nbsp;из&nbsp;1080&nbsp;риэлторов Москвы", "Аттестованный риэлтор-эксперт РГР"),
    ("РГР Топ-4&nbsp;из&nbsp;1080&nbsp;риэлторов Москвы", "Аттестованный риэлтор-эксперт РГР"),
    ("РГР Топ-3 из&nbsp;1080 риэлторов Москвы", "Аттестованный риэлтор-эксперт РГР"),
    ("РГР Топ-3 из 1080 риэлторов реестра Москвы", "Аттестованный риэлтор-эксперт РГР"),
    ("РГР Топ-3 из 1080 риэлторов реестра", "Аттестованный риэлтор-эксперт РГР"),
    ("РГР Топ-3&nbsp;из&nbsp;1080&nbsp;риэлторов реестра", "Аттестованный риэлтор-эксперт РГР"),
    ("РГР Топ-3 из 1080 риэлторов Москвы", "Аттестованный риэлтор-эксперт РГР"),
    ("Вход в&nbsp;РГР Топ-3 Москвы", "Внесение в&nbsp;реестр РГР"),
    ("РГР Топ-3 Москвы", "Аттестованный риэлтор-эксперт РГР"),
    ("РГР Топ-3&nbsp;из&nbsp;1080", "Аттестованный риэлтор-эксперт РГР"),
    ("РГР Топ-4&nbsp;из&nbsp;1080", "Аттестованный риэлтор-эксперт РГР"),
    ("РГР Топ-3 из 1080", "Аттестованный риэлтор-эксперт РГР"),
    ("РГР Топ-4 из 1080", "Аттестованный риэлтор-эксперт РГР"),
    ("РГР Топ-3&nbsp;/&nbsp;1080", "Аттестованный риэлтор-эксперт РГР"),
    ("РГР Топ-4&nbsp;/&nbsp;1080", "Аттестованный риэлтор-эксперт РГР"),
    ("Эксперт РГР Топ-3", "Аттестованный риэлтор-эксперт РГР"),
    ("Эксперт РГР Топ-4", "Аттестованный риэлтор-эксперт РГР"),
    ("РГР Топ-3", "Аттестованный риэлтор-эксперт РГР"),
    ("РГР Топ-4", "Аттестованный риэлтор-эксперт РГР"),
    # ещё один неподтверждаемый рейтинг, в другой форме
    ("№3</div><div class=\"hm-stat__l\">в&nbsp;РГР Топ-10 из&nbsp;1080 Москвы",
     "РГР</div><div class=\"hm-stat__l\">аттестованный риэлтор-эксперт, реестр"),
    ("в&nbsp;РГР Топ-10 <br>из&nbsp;1080 Москвы", "аттестованный риэлтор-эксперт, реестр"),
    # бренд-цифра: в проде «20+ лет», в порте осталась «23 года»
    ("Один эксперт, 23 года.", "Один эксперт, 20+ лет."),
    ("23 года, 500+ сделок", "20+ лет, 500+ сделок"),
    ("23 года в премиум-сегменте", "20+ лет в премиум-сегменте"),
    ("23&nbsp;года практики", "20+&nbsp;лет практики"),
    ("23 года практики", "20+ лет практики"),
    ("23&nbsp;года", "20+&nbsp;лет"),
]

# Та же сломанная фраза уже уехала в прод прошлой заменой — чиним и там.
PROD_BROKEN = [("Вход в&nbsp;Аттестованный риэлтор-эксперт РГР.", "Внесение в&nbsp;реестр РГР.")]


def main():
    dry = "--dry" in sys.argv
    n_schema = n_rgr = n_canon = 0

    for p in sorted(glob.glob(os.path.join(DATA, "*.html"))):
        s = open(p, encoding="utf-8").read()
        orig = s

        if "ОриентирOrHistoricalBuilding" in s:
            s = s.replace("ОриентирOrHistoricalBuilding", "LandmarkOrHistoricalBuilding")
            n_schema += 1

        had_rgr = "РГР Топ-" in s
        for a, b in RGR:
            s = s.replace(a, b)
        if had_rgr:
            n_rgr += 1

        # canonical/og:url/schema url: /avangard/ → /modernizm/ (живые адреса)
        if "beloliptsev.ru/avangard/" in s:
            s = s.replace("beloliptsev.ru/avangard/", "beloliptsev.ru/modernizm/")
            n_canon += 1
        s = s.replace('href="/avangard/', 'href="/modernizm/')

        if s != orig and not dry:
            open(p, "w", encoding="utf-8").write(s)

    n_prod = 0
    for p in sorted(glob.glob(os.path.join(BASE, "deploy", "**", "index.html"), recursive=True)):
        s = open(p, encoding="utf-8").read()
        o = s
        for a, b in PROD_BROKEN:
            s = s.replace(a, b)
        if s != o:
            n_prod += 1
            if not dry:
                open(p, "w", encoding="utf-8").write(s)

    print(f"  схема LandmarkOrHistoricalBuilding восстановлена: {n_schema} файлов")
    print(f"  рейтинг РГР приведён к формулировке прода:        {n_rgr} файлов")
    print(f"  canonical переведён на живые адреса /modernizm/:  {n_canon} файлов")
    print(f"  сломанная фраза починена в проде:                 {n_prod} файлов")
    print(f"\n{'(DRY) ' if dry else ''}готово")
    return 0


if __name__ == "__main__":
    sys.exit(main())
