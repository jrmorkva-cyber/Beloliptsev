REPL = GEO + ANGL

# ── §8: число + единица → неразрывный пробел (только в текст-узлах) ──────────
UNIT = re.compile(r"(\d)\s(млрд|млн|тыс|м²|км²|км|квартир\w*|этаж\w*|год\w*|лет|мин|₽|%|м)\b")

def fix_nbsp(html):
    return re.sub(r">([^<]*)<", lambda m: ">" + UNIT.sub(r"\1&nbsp;\2", m.group(1)) + "<", html)

def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    dry = "--dry" in sys.argv
    if not args:
        print("Usage: python rita-patch.py <путь-к-deploy> [--dry]"); return 1
    root = args[0]
    files = []
    for dp, _, fns in os.walk(root):
        for fn in fns:
            if fn.endswith(".html"):
                files.append(os.path.join(dp, fn))
    print(f"{'(DRY) ' if dry else ''}Папка: {root} — {len(files)} .html\n")
    changed = total = 0
    for f in files:
        s = open(f, encoding="utf-8").read()
        n = 0
        for a, b in REPL:
            c = s.count(a)
            if c:
                s = s.replace(a, b); n += c
        before_nbsp = s
        s = fix_nbsp(s)
        nb = len(UNIT.findall("".join(re.findall(r">([^<]*)<", before_nbsp)))) - \
             len(UNIT.findall("".join(re.findall(r">([^<]*)<", s))))
        n += max(0, nb)
        if n:
            if not dry:
                open(f, "w", encoding="utf-8").write(s)
            changed += 1; total += n
            print(f"  {os.path.relpath(f, root):<55} {n} замен")
    print(f"\n{'(DRY) ' if dry else ''}ИТОГО: {changed} файлов, {total} замен")
    return 0

if __name__ == "__main__":
    sys.exit(main())
