def flexible(s):
    return re.compile(r"(?:\s|&nbsp;)".join(re.escape(w) for w in s.split()))


SHORT = ("в во на за по до от из с со к о об у и а но не ни что как для при без над под про через "
         "это его её их том той тех").split()
UNITS = "млн|млрд|тыс|м²|км²|км|м|лет|мин|год\\w*|этаж\\w*|квартир\\w*|мест|₽|%"


def nb(t):
    t = re.sub(r"(?<![\w&;])(%s)\s+(?=[«\w])" % "|".join(SHORT), r"\1&nbsp;", t, flags=re.I)
    return re.sub(r"(\d)\s(%s)\b" % UNITS, r"\1&nbsp;\2", t)


def main():
    dry = "--dry" in sys.argv
    done = miss = 0

    # подпись заглушки, оставшаяся от донора во всех шести файлах
    for slug in NEW:
        p = os.path.join(BASE, "deploy", "modernizm", slug, "index.html")
        s = open(p, encoding="utf-8").read()
        if ">ДОМ ИСАКОВА<" in s:
            s = s.replace(">ДОМ ИСАКОВА<", ">%s<" % TITLES[slug])
            if not dry:
                open(p, "w", encoding="utf-8").write(s)
            done += 1
            print(f"  ✅ {slug}: подпись заглушки → {TITLES[slug]}")

    for slug, old, new in FIX:
        p = os.path.join(BASE, "deploy", "modernizm", slug, "index.html")
        s = open(p, encoding="utf-8").read()
        rx = flexible(old)
        n = len(rx.findall(s))
        if not n:
            miss += 1
            print(f"  ⚠️  {slug}: не найдено «{old[:56]}»")
            continue
        s = rx.sub(lambda _: nb(new), s)
        if not dry:
            open(p, "w", encoding="utf-8").write(s)
        done += n
        print(f"  ✅ {slug}: {n}× «{old[:46]}…»")

    print(f"\n{'(DRY) ' if dry else ''}заменено: {done}, не найдено: {miss}")
    return 1 if miss else 0


if __name__ == "__main__":
    sys.exit(main())
