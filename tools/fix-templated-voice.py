def main():
    dry = "--dry" in sys.argv
    rx = re.compile(r'(<h4>Закрытые предложения</h4>.*?<div class="st-faq__inner"><p>)(.*?)(</p>)', re.S)
    rx2 = re.compile(r'(<h4>Тип перекрытий и&nbsp;ипотека</h4>.*?<div class="st-faq__inner"><p>)(.*?)(</p>)', re.S)
    changed = 0
    for slug, text in MORTGAGE.items():
        p = os.path.join(BASE, "deploy", "modernizm", slug, "index.html")
        if not os.path.exists(p):
            continue
        s = open(p, encoding="utf-8").read()
        if rx2.search(s):
            s = rx2.sub(lambda m: m.group(1) + text + m.group(3), s, count=1)
            if not dry:
                open(p, "w", encoding="utf-8").write(s)
            print(f"  ✅ {slug} · карточка про ипотеку")
    for slug, text in NEW.items():
        p = os.path.join(BASE, "deploy", "modernizm", slug, "index.html")
        if not os.path.exists(p):
            print(f"  пропуск: нет {slug}"); continue
        s = open(p, encoding="utf-8").read()
        if not rx.search(s):
            print(f"  ⚠️  {slug}: карточка «Закрытые предложения» не найдена"); continue
        s2 = rx.sub(lambda m: m.group(1) + text + m.group(3), s, count=1)
        if s2 == s:
            print(f"  = {slug}: без изменений"); continue
        if not dry:
            open(p, "w", encoding="utf-8").write(s2)
        changed += 1
        print(f"  ✅ {slug}")
    print(f"\n{'(DRY) ' if dry else ''}страниц расшаблонено: {changed}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
