SHORT = ("в во на за по до от из с со к о об у и а но не ни что как для при без над под про через "
         "это его её их том той тех").split()
UNITS = "млн|млрд|тыс|м²|км²|км|м|лет|мин|год\\w*|этаж\\w*|квартир\\w*|мест|₽|%"


def nb(t):
    """Та же типографика, что применялась при сборке страниц."""
    t = re.sub(r"(?<![\w&;])(%s)\s+(?=[«\w])" % "|".join(SHORT), r"\1&nbsp;", t, flags=re.I)
    return re.sub(r"(\d)\s(%s)\b" % UNITS, r"\1&nbsp;\2", t)


def flexible(s):
    """Шаблон, где любой пробел исходной строки совпадает и с пробелом, и с &nbsp;."""
    return re.compile(r"(?:\s|&nbsp;)".join(re.escape(w) for w in s.split()))


def main():
    dry = "--dry" in sys.argv
    total = miss = 0
    for slug, pairs in HEADINGS.items():
        p = os.path.join(BASE, "deploy", "modernizm", slug, "index.html")
        if not os.path.exists(p):
            print(f"  нет файла: {slug}"); continue
        s = open(p, encoding="utf-8").read()
        orig = s
        for old, new in pairs + PARAGRAPHS.get(slug, []):
            rx = flexible(old)
            if rx.search(s):
                s = rx.sub(lambda _: nb(new), s, count=1)
                total += 1
            else:
                miss += 1
                print(f"  ⚠️  {slug}: не найдено «{old[:52]}»")
        if s != orig and not dry:
            open(p, "w", encoding="utf-8").write(s)
    print(f"\n{'(DRY) ' if dry else ''}заменено: {total}, не найдено: {miss}")
    return 1 if miss else 0


if __name__ == "__main__":
    sys.exit(main())
